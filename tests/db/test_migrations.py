async def _tables(url: URL) -> set[object]:
    rows = await fetch_all(
        url,
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema = 'public' AND table_name <> 'alembic_version'",
    )
    return {row[0] for row in rows}


async def _enum_types(url: URL) -> set[object]:
    rows = await fetch_all(
        url,
        "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
        "WHERE t.typtype = 'e' AND n.nspname = 'public'",
    )
    return {row[0] for row in rows}


async def _enum_labels(url: URL, type_name: str) -> list[object]:
    rows = await fetch_all(
        url,
        "SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid "
        "WHERE t.typname = :type_name ORDER BY e.enumsortorder",
        {"type_name": type_name},
    )
    return [row[0] for row in rows]


async def _default_mode_rows(url: URL) -> list[tuple[object, ...]]:
    return await fetch_all(
        url,
        "SELECT name, prompt_fragment, few_shot_examples, enabled FROM modes WHERE name = :name",
        {"name": DEFAULT_MODE_NAME},
    )


async def test_upgrade_on_a_clean_database_creates_the_schema(
    database_url: URL, alembic_config: Config
) -> None:
    assert await _tables(database_url) == set()

    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    assert await _tables(database_url) == TABLES
    assert await _enum_types(database_url) == ENUM_TYPES


async def test_downgrade_removes_everything_and_upgrade_works_again(
    database_url: URL, alembic_config: Config
) -> None:
    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    await asyncio.to_thread(command.downgrade, alembic_config, "base")

    assert await _tables(database_url) == set()
    assert await _enum_types(database_url) == set()

    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    assert await _tables(database_url) == TABLES
    assert len(await _default_mode_rows(database_url)) == 1


