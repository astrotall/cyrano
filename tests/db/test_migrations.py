async def _insert_outbox_rows_at_0004(url: URL) -> None:
    await execute(
        url,
        f"INSERT INTO contacts (id, tg_id) VALUES ({BACKFILL_CONTACT_ID}, {FAKE_TELEGRAM_ID})",  # noqa: S608
    )
    for send_at, state in BACKFILL_ROWS:
        await execute(
            url,
            "INSERT INTO scheduled_messages (contact_id, text, source, send_at, state) "  # noqa: S608
            f"VALUES ({BACKFILL_CONTACT_ID}, 'x', 'manual_test', '{send_at.isoformat()}', "
            f"'{state}')",
        )


async def _due_at_column(url: URL) -> list[tuple[object, ...]]:
    return await fetch_all(
        url,
        "SELECT is_nullable, data_type, column_default FROM information_schema.columns "
        "WHERE table_name = 'scheduled_messages' AND column_name = 'due_at'",
    )


async def test_revision_0005_backfills_every_existing_row_with_its_send_at(
    database_url: URL, alembic_config: Config
) -> None:
    await asyncio.to_thread(command.upgrade, alembic_config, "0004")
    await _insert_outbox_rows_at_0004(database_url)

    await asyncio.to_thread(command.upgrade, alembic_config, "0005")

    rows = await fetch_all(
        database_url, "SELECT send_at, due_at, state FROM scheduled_messages ORDER BY id"
    )
    assert rows == [(send_at, send_at, state) for send_at, state in BACKFILL_ROWS]
    assert await _due_at_column(database_url) == [("NO", "timestamp with time zone", None)]


async def test_revision_0005_downgrades_to_0004_keeps_the_rows_and_upgrades_again(
    database_url: URL, alembic_config: Config
) -> None:
    await asyncio.to_thread(command.upgrade, alembic_config, "0004")
    await _insert_outbox_rows_at_0004(database_url)
    await asyncio.to_thread(command.upgrade, alembic_config, "0005")

    await asyncio.to_thread(command.downgrade, alembic_config, "0004")

    assert await _due_at_column(database_url) == []
    assert await fetch_all(
        database_url, "SELECT send_at, state FROM scheduled_messages ORDER BY id"
    ) == [(send_at, state) for send_at, state in BACKFILL_ROWS]

    await asyncio.to_thread(command.upgrade, alembic_config, "0005")

    assert await _due_at_column(database_url) == [("NO", "timestamp with time zone", None)]
    rows = await fetch_all(database_url, "SELECT send_at, due_at FROM scheduled_messages")
    assert all(send_at == due_at for send_at, due_at in rows)
    assert len(rows) == len(BACKFILL_ROWS)


