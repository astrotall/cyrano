from __future__ import annotations

import asyncio
import io
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy.engine import URL

from cyrano.domain.enums import ContactStatus, MessageDirection
from cyrano.domain.models import DEFAULT_MODE_NAME
from tests.conftest import SECRET_VALUES
from tests.db.conftest import ALEMBIC_INI, execute, fetch_all

TABLES = {"contacts", "messages", "modes"}
ENUM_TYPES = {"contact_status", "message_direction"}
TIMESTAMP_COLUMNS = {
    ("contacts", "created_at"),
    ("contacts", "last_message_at"),
    ("contacts", "updated_at"),
    ("messages", "created_at"),
    ("modes", "created_at"),
    ("modes", "updated_at"),
}
EXPECTED_CONSTRAINTS = {
    "pk_contacts",
    "pk_messages",
    "pk_modes",
    "uq_contacts_tg_id",
    "uq_modes_name",
    "uq_messages_contact_id_tg_message_id",
    "fk_contacts_mode_id_modes",
    "fk_messages_contact_id_contacts",
}
EXPECTED_INDEXES = {"ix_contacts_status", "ix_messages_contact_id_created_at"}


async def _tables(url: URL) -> set[object]:
    rows = await fetch_all(
        url,
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema = 'public' AND table_name <> 'alembic_version'",
    )
    return {row[0] for row in rows}


async def _enum_types(url: URL) -> set[object]:
    rows = await fetch_all(
        url,
        "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
        "WHERE t.typtype = 'e' AND n.nspname = 'public'",
    )
    return {row[0] for row in rows}


async def _enum_labels(url: URL, type_name: str) -> list[object]:
    rows = await fetch_all(
        url,
        "SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid "
        "WHERE t.typname = :type_name ORDER BY e.enumsortorder",
        {"type_name": type_name},
    )
    return [row[0] for row in rows]


async def _default_mode_rows(url: URL) -> list[tuple[object, ...]]:
    return await fetch_all(
        url,
        "SELECT name, prompt_fragment, few_shot_examples, enabled FROM modes WHERE name = :name",
        {"name": DEFAULT_MODE_NAME},
    )


async def test_upgrade_on_a_clean_database_creates_the_schema(
    database_url: URL, alembic_config: Config
) -> None:
    assert await _tables(database_url) == set()

    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    assert await _tables(database_url) == TABLES
    assert await _enum_types(database_url) == ENUM_TYPES


async def test_downgrade_removes_everything_and_upgrade_works_again(
    database_url: URL, alembic_config: Config
) -> None:
    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    await asyncio.to_thread(command.downgrade, alembic_config, "base")

    assert await _tables(database_url) == set()
    assert await _enum_types(database_url) == set()

    await asyncio.to_thread(command.upgrade, alembic_config, "head")

    assert await _tables(database_url) == TABLES
    assert len(await _default_mode_rows(database_url)) == 1


async def test_alembic_check_reports_no_drift(migrated_url: URL, alembic_config: Config) -> None:
    await asyncio.to_thread(command.check, alembic_config)


async def test_alembic_check_detects_drift(migrated_url: URL, alembic_config: Config) -> None:
    await execute(migrated_url, "DROP INDEX ix_contacts_status")

    with pytest.raises(AutogenerateDiffsDetected):
        await asyncio.to_thread(command.check, alembic_config)


async def test_enum_labels_match_the_domain(migrated_url: URL) -> None:
    assert await _enum_labels(migrated_url, "contact_status") == [s.value for s in ContactStatus]
    assert await _enum_labels(migrated_url, "message_direction") == [
        d.value for d in MessageDirection
    ]


async def test_constraint_and_index_names_follow_the_convention(migrated_url: URL) -> None:
    constraints = await fetch_all(
        migrated_url,
        "SELECT c.conname FROM pg_constraint c JOIN pg_namespace n ON n.oid = c.connamespace "
        "WHERE n.nspname = 'public' AND c.conname <> 'alembic_version_pkc'",
    )
    indexes = await fetch_all(
        migrated_url,
        "SELECT indexname FROM pg_indexes WHERE schemaname = 'public' AND indexname LIKE 'ix_%'",
    )

    assert {row[0] for row in constraints} == EXPECTED_CONSTRAINTS
    assert {row[0] for row in indexes} == EXPECTED_INDEXES


async def test_every_timestamp_column_is_timestamptz(migrated_url: URL) -> None:
    rows = await fetch_all(
        migrated_url,
        "SELECT table_name, column_name, data_type FROM information_schema.columns "
        "WHERE table_schema = 'public' AND data_type LIKE 'timestamp%'",
    )

    assert {(row[0], row[1]) for row in rows} == TIMESTAMP_COLUMNS
    assert {row[2] for row in rows} == {"timestamp with time zone"}


async def test_default_mode_is_seeded_once_with_an_empty_examples_list(migrated_url: URL) -> None:
    rows = await _default_mode_rows(migrated_url)

    assert len(rows) == 1
    name, prompt_fragment, few_shot_examples, enabled = rows[0]
    assert name == DEFAULT_MODE_NAME
    assert prompt_fragment
    assert few_shot_examples == []
    assert enabled is True


async def test_seed_is_idempotent(migrated_url: URL, alembic_config: Config) -> None:
    head = ScriptDirectory.from_config(alembic_config).get_revision("head")
    assert head is not None
    seed: str = head.module.SEED_DEFAULT_MODE

    await execute(migrated_url, seed)
    await execute(migrated_url, seed)

    assert len(await _default_mode_rows(migrated_url)) == 1


def test_offline_upgrade_prints_sql_without_secrets_or_log_lines(full_env: dict[str, str]) -> None:
    output = io.StringIO()

    command.upgrade(Config(ALEMBIC_INI, output_buffer=output), "head", sql=True)

    sql = output.getvalue()
    assert "CREATE TABLE contacts" in sql
    assert "ON CONFLICT (name) DO NOTHING" in sql
    assert '"level"' not in sql
    for secret in SECRET_VALUES:
        assert secret not in sql


def test_alembic_without_configuration_exits_with_the_readable_error(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, alembic_config: Config
) -> None:
    monkeypatch.chdir(tmp_path)

    with pytest.raises(SystemExit, match="Missing required environment variables"):
        command.upgrade(alembic_config, "head")
