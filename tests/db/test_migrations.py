def test_offline_upgrade_prints_sql_without_secrets_or_log_lines(full_env: dict[str, str]) -> None:
    output = io.StringIO()

    command.upgrade(Config(ALEMBIC_INI, output_buffer=output), "head", sql=True)

    sql = output.getvalue()
    assert "CREATE TABLE contacts" in sql
    assert "ON CONFLICT (name) DO NOTHING" in sql
    assert "UPDATE scheduled_messages SET due_at = send_at" in sql
    assert '"level"' not in sql
    for secret in SECRET_VALUES:
        assert secret not in sql


